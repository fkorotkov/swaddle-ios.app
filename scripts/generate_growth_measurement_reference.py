#!/usr/bin/env python3
"""Reproduce offline length/head LMS data and independent published-centile tests."""
import argparse
import hashlib
import json
from pathlib import Path

from generate_who_weight_reference import rows

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ReferenceData/GrowthMeasurements"


def generate():
    for source in json.loads((SOURCE / "sources.json").read_text())["files"]:
        assert hashlib.sha256((SOURCE / source["file"]).read_bytes()).hexdigest() == source["sha256"]
    data = ["// Generated by scripts/generate_growth_measurement_reference.py. Do not hand-edit.",
            "// Official WHO daily LMS, days 0...1856. Source workbooks are not app resources.",
            "// Length through day 730; standing height from day 731. Centimeters.",
            "enum WHOMeasurementReference {"]
    fixtures = ["@testable import LittleLogCore", "",
                "// Independent WHO percentile workbooks; values rounded to 0.001 cm.",
                "struct WHOMeasurementFixture: Sendable {",
                "  let metric: GrowthMeasurementMetric", "  let sex: GrowthReferenceSex",
                "  let day: Int", "  let percentile: Double", "  let centimeters: Double", "}",
                "let whoMeasurementFixtures: [WHOMeasurementFixture] = ["]
    for prefix, metric in [("lhfa", "length"), ("hcfa", "headCircumference")]:
        for label, sex in [("boys", "male"), ("girls", "female")]:
            table = rows(SOURCE / f"{prefix}-{label}-zscore-expanded-tables.xlsx")
            assert table[0][:4] == ["Day", "L", "M", "S"] and len(table) == 1858
            data.append(f"  static let {metric}{sex.title()}: [MeasurementForAge.LMS] = [")
            for day, row in enumerate(table[1:]):
                assert row[0] == day
                data.append(f"    .init(l: {row[1]:.4f}, m: {row[2]:.4f}, s: {row[3]:.5f}), // {day}")
            data.append("  ]")
            centiles = rows(SOURCE / f"{prefix}-{label}-percentiles-expanded-tables.xlsx")
            assert centiles[0][0] in ["Day", "Age"] and centiles[0][1:4] == ["L", "M", "S"]
            for day in [0, 1, 7, 30, 60, 90, 180, 365, 730, 731, 732, 1096, 1826]:
                row = centiles[day + 1]
                assert row[0] == day
                for p in [3, 15, 50, 85, 97]:
                    value = row[centiles[0].index(f"P{p}")]
                    fixtures.append(f"  .init(metric: .{metric}, sex: .{sex}, day: {day}, percentile: {p}, centimeters: {value:.3f}),")
    data.append("}")
    fixtures.append("]")
    return {
        ROOT / "BabyActivityRecorder/Domain/WHOMeasurementReference.swift": "\n".join(data) + "\n",
        ROOT / "Tests/GrowthMeasurementReferenceFixtures.swift": "\n".join(fixtures) + "\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for path, content in generate().items():
        if options.check:
            assert path.read_text() == content, f"Regenerate {path}"
        else:
            path.write_text(content)
    print("Verified 7,428 WHO daily LMS rows and 260 WHO centiles.")
