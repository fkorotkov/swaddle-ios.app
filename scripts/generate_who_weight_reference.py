#!/usr/bin/env python3
"""Reproduce offline Swift tables from the pinned WHO workbooks, without dependencies."""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ReferenceData/WHO"
NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def rows(path):
    with ZipFile(path) as book:
        strings = ["".join(item.itertext()) for item in ET.fromstring(
            book.read("xl/sharedStrings.xml")).findall("s:si", NS)]
        result = []
        for row in ET.fromstring(book.read("xl/worksheets/sheet1.xml")).findall("s:sheetData/s:row", NS):
            values = []
            for cell in row.findall("s:c", NS):
                value = cell.find("s:v", NS)
                values.append(strings[int(value.text)] if cell.get("t") == "s" else float(value.text))
            result.append(values)
        return result


def main():
    for item in json.loads((SOURCE / "sources.json").read_text())["files"]:
        assert hashlib.sha256((SOURCE / item["file"]).read_bytes()).hexdigest() == item["sha256"]
    generated = ["// Generated by scripts/generate_who_weight_reference.py. Do not hand-edit.",
                 "// WHO Child Growth Standards (2006), daily weight-for-age LMS, days 0...731.",
                 "// Provenance and unmodified workbooks: ReferenceData/WHO/.",
                 "enum WHOWeightReference {"]
    fixtures = ["// Generated from the independent WHO percentile workbooks (weights rounded to 0.001 kg).",
                "// This tests the calculator against published centiles, not against its own inverse.",
                "struct WHOWeightReferenceFixture: Sendable {",
                "  let sex: GrowthReferenceSex", "  let day: Int", "  let percentile: Double",
                "  let kilograms: Double", "}", "let whoWeightReferenceFixtures: [WHOWeightReferenceFixture] = ["]
    for label, sex in [("boys", "male"), ("girls", "female")]:
        source = rows(SOURCE / f"wfa-{label}-zscore-expanded-tables.xlsx")
        assert source[0][:4] == ["Day", "L", "M", "S"]
        assert len(source) == 1858
        generated.append(f"  static let {sex}: [WHOWeightForAge.LMS] = [")
        for day, row in enumerate(source[1:733]):
            assert row[0] == day
            # WHO publishes these coefficients at 4, 4, and 5 decimal places.
            assert all(abs(value - round(value, places)) < 1e-12
                       for value, places in zip(row[1:4], [4, 4, 5]))
            generated.append(f"    .init(l: {row[1]:.4f}, m: {row[2]:.4f}, s: {row[3]:.5f}), // {day}")
        generated.append("  ]")
        centiles = rows(SOURCE / f"wfa-{label}-percentiles-expanded-tables.xlsx")
        assert centiles[0][:4] == ["Age", "L", "M", "S"]
        for day in [0, 1, 7, 30, 60, 90, 180, 365, 730, 731]:
            row = centiles[day + 1]
            assert row[0] == day
            for percentile in [3, 15, 50, 85, 97]:
                kg = row[centiles[0].index(f"P{percentile}")]
                fixtures.append(f"  .init(sex: .{sex}, day: {day}, percentile: {percentile}, kilograms: {kg:.3f}),")
    generated.append("}")
    fixtures.append("]")
    (ROOT / "BabyActivityRecorder/Domain/WHOWeightReference.swift").write_text("\n".join(generated) + "\n")
    # Test data lives outside the app; raw workbooks are never shipped in the bundle.
    (ROOT / "Tests/WHOWeightReferenceFixtures.swift").write_text(
        "@testable import LittleLogCore\n\n" + "\n".join(fixtures) + "\n")
    print("Generated 1,464 daily LMS rows and 100 independent published-centile fixtures.")


if __name__ == "__main__":
    main()
