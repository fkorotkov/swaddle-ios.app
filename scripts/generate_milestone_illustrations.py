#!/usr/bin/env python3
"""Generate the complete offline Swaddle milestone illustration collection.

The approved wave, crawl, and stack studies share their original character rig
with the remaining skill-specific scenes. All loops reset beneath a gentle
fade so one-way skills never run backwards. No raster or remote art is used.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

from milestone_illustration_art import FPS, FRAMES, Scene
from milestone_illustration_scenes import CatalogScene
from milestone_illustration_cast import assignments, bake, distribution

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "BabyActivityRecorder/Assets.xcassets/MilestoneIllustrations"
REFERENCE = ROOT / "ReferenceData/MilestoneIllustrations"
SWIFT = ROOT / "BabyActivityRecorder/Design/MilestoneIllustrationCatalog.swift"
REVIEWED = {
    "cdc-12-bye_bye": ("wave", 95),
    "who-crawling": ("crawl", 112),
    "cdc-15-stacks_small": ("stack", 147),
}


def catalog():
    skills = json.loads((ROOT / "ReferenceData/Milestones/cdc-checklists.json").read_text())["skills"]
    source = (ROOT / "BabyActivityRecorder/Domain/Milestones.swift").read_text()
    skills += [dict(id="who-" + slug, title=title) for slug, title in
               re.findall(r'motor\("([^"]+)", "([^"]+)"', source)]
    if len({s["id"] for s in skills}) != len(skills):
        raise ValueError("Duplicate milestone ID in the app catalog")
    return skills


def storyboards():
    boards = {}
    for line in (REFERENCE / "storyboards.tsv").read_text().splitlines():
        if not line or line.startswith("#"): continue
        skill_id, action, prop, description = line.split("|", 3)
        if skill_id in boards: raise ValueError("Duplicate storyboard: " + skill_id)
        boards[skill_id] = dict(action=action, prop=prop, description=description)
    return boards


def outputs():
    skills, boards = catalog(), storyboards()
    catalog_ids = {s["id"] for s in skills}
    if catalog_ids != boards.keys():
        raise ValueError(f"Storyboard coverage mismatch. Missing: {catalog_ids - boards.keys()}; unexpected: {boards.keys() - catalog_ids}")
    files, manifest, descriptions, posters = {}, [], [], []
    info = dict(info=dict(author="xcode", version=1))
    files[ASSETS / "Contents.json"] = json.dumps(info, indent=2) + "\n"
    scenes = []
    for skill in skills:
        skill_id, board = skill["id"], boards[skill["id"]]
        if skill_id in REVIEWED:
            action, poster = REVIEWED[skill_id]
            illustration = Scene(skill_id).build(action, poster, board["description"])
        else:
            illustration = CatalogScene(skill_id).compose(skill, board)
            poster = illustration["markers"][0]["tm"]
        scenes.append(illustration)
    casts = assignments(scenes)
    for skill, illustration in zip(skills, scenes):
        skill_id, board = skill["id"], boards[skill["id"]]
        poster = illustration["markers"][0]["tm"]
        illustration = bake(illustration, casts[skill_id])
        name = "milestone-" + skill_id
        data = json.dumps(illustration, ensure_ascii=False, separators=(",", ":")) + "\n"
        folder = ASSETS / (name + ".dataset")
        files[folder / "illustration.json"] = data
        files[folder / "Contents.json"] = json.dumps(dict(data=[dict(filename="illustration.json", idiom="universal")], **info), indent=2) + "\n"
        manifest.append(dict(id=skill_id, title=skill["title"], asset=name, action=board["action"],
                             description=board["description"], posterFrame=poster, duration=FRAMES / FPS,
                             loop="gentle hidden reset", cast=casts[skill_id],
                             sha256=hashlib.sha256(data.encode()).hexdigest()))
        descriptions.append(f'    "{skill_id}": String(localized: {json.dumps(board["description"], ensure_ascii=False)}),')
        posters.append(f'    "{skill_id}": {poster},')
    files[REFERENCE / "manifest.json"] = json.dumps(dict(version=5, status="Complete catalog; diverse cast and automatically looping while visible",
        artwork="Original Swaddle vector illustrations", adultVariants=["neutral", "female", "male"],
        casting="Balanced, deterministically shuffled artwork; no ethnicity or appearance profile data",
        distribution=distribution(casts),
        illustrations=manifest), ensure_ascii=False, indent=2) + "\n"
    files[SWIFT] = '''// Generated by scripts/generate_milestone_illustrations.py. Original Swaddle artwork.
import Foundation
enum MilestoneIllustrationCatalog {
  static let descriptions: [String: String] = [
''' + "\n".join(descriptions) + '''
  ]
  private static let posterFrames: [String: Double] = [
''' + "\n".join(posters) + '''
  ]
  static func posterFrame(for skill: MilestoneSkill) -> Double { posterFrames[skill.id] ?? 0 }
  static func assetName(for skill: MilestoneSkill) -> String { "milestone-" + skill.id }
}
'''
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, stale = outputs(), []
    for file, content in files.items():
        if args.check:
            if not file.exists() or file.read_text() != content: stale.append(str(file.relative_to(ROOT)))
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content)
    unexpected = set(ASSETS.glob("*.dataset/illustration.json")) - files.keys()
    if unexpected: raise SystemExit("Unexpected generated scenes: " + ", ".join(str(f.relative_to(ROOT)) for f in unexpected))
    if stale: raise SystemExit("Stale illustration files: " + ", ".join(stale))
    art = [c for f, c in files.items() if f.name == "illustration.json"]
    print(f"{'Verified' if args.check else 'Created'} {len(art)} milestone scenes; {sum(len(c.encode()) for c in art):,} bytes of vector art.")


if __name__ == "__main__":
    main()
